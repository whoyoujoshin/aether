"""Byte-for-byte agreement with the chain's Go implementation
(clients/testdata/vectors.json, generated by `go test ./clients/vectors`)."""

import json
import pathlib
import unittest

from aether_client import (DIRECTORY_ADDRESS, MSG_EXEC_TYPE_URL, Key, SendGrant, build_send, build_tx, decode_send_grant, exec_send_msg,
                           format_aeth, grant_send_msg, is_address, memo_of, parse_amount, pull_signing_message, signing_message,
                           transfers)
from aether_client.proto import Writer

V = json.loads((pathlib.Path(__file__).resolve().parents[2] / "testdata" / "vectors.json").read_text())


class Vectors(unittest.TestCase):
    def setUp(self):
        self.key = Key.from_mnemonic(V["key"]["mnemonic"])

    def test_key_and_address(self):
        self.assertEqual(self.key.seed.hex(), V["key"]["seed"])
        self.assertEqual(self.key.public_key.hex(), V["key"]["pubKey"])
        self.assertEqual(self.key.address, V["key"]["address"])

    def test_signatures_interoperate(self):
        msg = bytes.fromhex(V["signature"]["message"])
        self.assertTrue(Key.verify(self.key.public_key, msg, bytes.fromhex(V["signature"]["signature"])))
        self.assertEqual(self.key.sign(msg, deterministic=True).hex(), V["signature"]["signature"])
        mine = self.key.sign(msg)
        self.assertTrue(Key.verify(self.key.public_key, msg, mine))
        self.assertFalse(Key.verify(self.key.public_key, b"other", mine))

    def test_transactions_are_byte_identical(self):
        for t in V["txs"]:
            s = build_send(self.key, chain_id=t["chainId"], account_number=t["accountNumber"], sequence=t["sequence"],
                           to=t["to"], amount_uaeth=int(t["amountUaeth"]), memo=t["memo"], gas_limit=t["gasLimit"],
                           deterministic=True)
            self.assertEqual(s.body_bytes.hex(), t["bodyBytes"])
            self.assertEqual(s.auth_info_bytes.hex(), t["authInfoBytes"])
            self.assertEqual(s.sign_doc.hex(), t["signDoc"])
            self.assertEqual(s.signature.hex(), t["signature"])
            self.assertEqual(s.tx_bytes.hex(), t["txBytes"])
            self.assertEqual(s.hash, t["txHash"])
            self.assertEqual(memo_of(bytes.fromhex(t["txBytes"])), t["memo"])

    def test_prepaid_signing_message(self):
        p = V["prepaid"]
        msg = signing_message(network=p["Network"], pay_to=p["PayTo"], host=p["Host"], method=p["Method"], path=p["Path"],
                              body=p["body"].encode(), max_price=int(p["maxPrice"]), timestamp=p["timestamp"],
                              request_id=p["RequestID"], deposit_tx=p["DepositTx"])
        self.assertEqual(msg.hex(), p["message"])

    def test_pull(self):
        p = V["prepaid"]
        f = dict(network=p["Network"], pay_to=p["PayTo"], host=p["Host"], method=p["Method"], path=p["Path"], body=p["body"].encode(),
                 max_price=int(p["maxPrice"]), timestamp=p["timestamp"], request_id=p["RequestID"], deposit_tx=p["DepositTx"])
        self.assertEqual(pull_signing_message(**f).hex(), V["pull"]["message"], "the deposit is ignored")
        self.assertNotEqual(pull_signing_message(**f), signing_message(**{**f, "deposit_tx": ""}), "domain-separated from prepaid")

        g = V["pull"]["grant"]
        grant = build_tx(self.key, [grant_send_msg(self.key.address, g["grantee"], int(g["limitUaeth"]), g["allowList"], g["expiration"])],
                         chain_id="aether-testnet-1", account_number=g["accountNumber"], sequence=g["sequence"], deterministic=True)
        self.assertEqual(grant.body_bytes.hex(), g["bodyBytes"])
        self.assertEqual(grant.tx_bytes.hex(), g["txBytes"])
        self.assertEqual(grant.hash, g["txHash"])

        e = V["pull"]["exec"]
        ex = build_tx(self.key, [exec_send_msg(self.key.address, e["granter"], e["to"], int(e["amountUaeth"]))], chain_id="aether-testnet-1",
                      account_number=e["accountNumber"], sequence=e["sequence"], memo=e["memo"], deterministic=True)
        self.assertEqual(ex.body_bytes.hex(), e["bodyBytes"])
        self.assertEqual(ex.tx_bytes.hex(), e["txBytes"])
        self.assertEqual(ex.hash, e["txHash"])

        req = Writer().string(1, self.key.address).string(2, g["grantee"]).string(3, "/cosmos.bank.v1beta1.MsgSend").finish()
        self.assertEqual(req.hex(), V["pull"]["grantsRequest"])
        self.assertEqual(decode_send_grant(bytes.fromhex(V["pull"]["grantsResponse"])), SendGrant(False, 750_000, g["allowList"], g["expiration"]))
        self.assertIsNone(decode_send_grant(b""))

    def test_queries_and_directory_address(self):
        self.assertEqual(Writer().string(1, V["key"]["address"]).finish().hex(), V["queries"]["accountInfoRequest"])
        self.assertEqual(Writer().string(1, V["key"]["address"]).string(2, "uaeth").finish().hex(), V["queries"]["balanceRequest"])
        self.assertEqual(DIRECTORY_ADDRESS, V["directoryAddress"])


class Basics(unittest.TestCase):
    def test_amounts(self):
        self.assertEqual(parse_amount("1.5 AETH"), 1_500_000)
        self.assertEqual(parse_amount("0100000uaeth"), 100_000)
        for bad in ["1500000", "1.0000001 AETH", "1.5 uaeth", "0 AETH", "1 BTC", "-1 AETH"]:
            with self.assertRaises(ValueError, msg=bad):
                parse_amount(bad)
        self.assertEqual(format_aeth(1_500_000), "1.5")
        self.assertEqual(format_aeth(1), "0.000001")

    def test_addresses(self):
        a = V["key"]["address"]
        self.assertTrue(is_address(a))
        self.assertFalse(is_address(a[:-1] + ("p" if a.endswith("q") else "q")))
        self.assertFalse(is_address("cosmos1qyqszqgpqyqszqgpqyqszqgpqyqszqgpjnp7du"))
        with self.assertRaises(ValueError):
            build_send(Key.from_mnemonic(V["key"]["mnemonic"]), chain_id="x", account_number=0, sequence=0, to="aether1bogus", amount_uaeth=1)

    def test_transfers_and_mnemonics(self):
        t = transfers([{"type": "transfer", "attributes": [{"key": "recipient", "value": "B"}, {"key": "sender", "value": "A"}, {"key": "amount", "value": "150uaeth"}]}])
        self.assertEqual((t[0].sender, t[0].recipient, t[0].amount_uaeth), ("A", "B", 150))
        with self.assertRaises(ValueError):
            Key.from_mnemonic(V["key"]["mnemonic"].rsplit(" ", 1)[0] + " zoo")
        key, phrase = Key.generate()
        self.assertEqual(len(phrase.split()), 24)
        self.assertEqual(Key.from_mnemonic(phrase).address, key.address)


if __name__ == "__main__":
    unittest.main()
